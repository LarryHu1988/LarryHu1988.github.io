import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';
import * as fontkit from 'fontkit';
import { site } from './paths.mjs';

export const manifestPath = resolve(site, 'content/font-subsets.json');
export const cssPath = resolve(site, 'app/generated-fonts.css');
export const basePath = '/fonts/noto-serif-sc.woff2';
export const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const relevant = /[\u0020-\u007e\u00a0\u00b7\u2010-\u2027\u3000-\u303f\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\uff00-\uffef\u{20000}-\u{2fa1f}]/u;

export function fontNeeds(directory = site) {
  const frequency = new Map();
  const critical = new Set();
  const catalogue = new Set();
  function add(text, important = false) {
    for (const char of text) if (relevant.test(char)) {
      frequency.set(char, (frequency.get(char) || 0) + 1);
      if (important) critical.add(char);
    }
  }
  function walk(folder, important) {
    for (const entry of readdirSync(folder, { withFileTypes: true })) {
      if (/ [0-9]+\./.test(entry.name)) continue;
      const path = resolve(folder, entry.name);
      if (entry.isDirectory()) walk(path, important);
      else if (/\.(?:tsx?|json)$/.test(entry.name) && !['image-previews.json', 'font-subsets.json'].includes(entry.name)) {
        const text = readFileSync(path, 'utf8');
        add(entry.name.endsWith('.json') ? JSON.stringify(JSON.parse(text)) : text, important || entry.name !== 'poetry-picture.json');
      }
    }
  }
  for (const folder of ['app', 'components', 'content']) walk(resolve(directory, folder), folder !== 'content');
  const issues = JSON.parse(readFileSync(resolve(directory, 'content/poetry-picture.json'), 'utf8'));
  for (const issue of [...issues.slice(0, 3), ...issues.slice(-5)]) add(issue.title + issue.author, true);
  for (const issue of issues) for (const char of issue.title + issue.author) if (relevant.test(char)) catalogue.add(char);
  return { required: new Set(frequency.keys()), critical, catalogue, frequency };
}

export function fontInfo(path, directory = site) {
  const bytes = readFileSync(resolve(directory, 'public' + path));
  const face = fontkit.create(bytes);
  const weight = face.variationAxes?.wght;
  if (!face.postscriptName?.startsWith('NotoSerifSC') || !weight || weight.min > 400 || weight.max < 700) {
    throw new Error(`Expected Noto Serif SC with real variable weights 400-700: ${path}`);
  }
  return { sha256: digest(bytes), characters: new Set(face.characterSet.map(point => String.fromCodePoint(point))), bytes: bytes.length };
}

export function unicodeRanges(characters) {
  const points = [...new Set([...characters].map(char => char.codePointAt(0)))].sort((a, b) => a - b);
  const ranges = [];
  for (let i = 0; i < points.length; i++) {
    const start = points[i];
    let end = start;
    while (points[i + 1] === end + 1) end = points[++i];
    const hex = point => point.toString(16).toUpperCase();
    ranges.push(`U+${hex(start)}${end === start ? '' : '-' + hex(end)}`);
  }
  return ranges.join(',');
}

export function fontCSS(manifest, base) {
  const faces = [{ path: basePath, characters: base.characters }, ...manifest.subsets];
  return '/* Generated by npm run fonts:sync. Do not edit by hand. */\n' + faces.map(face =>
    `@font-face { font-family: "Studio Serif"; src: url("${face.path}") format("woff2"); font-weight: 400 700; font-style: normal; font-display: swap; unicode-range: ${unicodeRanges(face.characters)}; }`,
  ).join('\n') + '\n';
}

export function inspectFonts(directory = site) {
  const base = fontInfo(basePath, directory);
  const manifestFile = resolve(directory, 'content/font-subsets.json');
  const manifest = existsSync(manifestFile) ? JSON.parse(readFileSync(manifestFile, 'utf8')) : { version: 1, baseSha256: base.sha256, subsets: [] };
  if (manifest.baseSha256 !== base.sha256) throw new Error('The base font changed; regenerate font subsets explicitly.');
  const covered = new Set(base.characters);
  for (const subset of manifest.subsets) {
    if (!/^\/fonts\/serif\/serif-[a-f0-9]{12}\.woff2$/.test(subset.path)) throw new Error('Invalid font subset path');
    const info = fontInfo(subset.path, directory);
    if (info.sha256 !== subset.sha256 || !subset.path.includes(info.sha256.slice(0, 12))) throw new Error(`Font checksum mismatch: ${subset.path}`);
    for (const char of subset.characters) {
      if (!info.characters.has(char)) throw new Error(`Font claims a missing character: ${char}`);
      if (covered.has(char)) throw new Error(`Overlapping font ranges: ${char}`);
      covered.add(char);
    }
  }
  const needs = fontNeeds(directory);
  const missing = [...needs.required].filter(char => !covered.has(char));
  return { base, manifest, covered, ...needs, missing };
}

export function checkFonts(directory = site) {
  const result = inspectFonts(directory);
  if (result.missing.length) throw new Error(`Chinese webfont is missing ${result.missing.length} characters (${result.missing.slice(0, 30).join('')}). Run npm run fonts:sync before publishing.`);
  const actualCSS = readFileSync(resolve(directory, 'app/generated-fonts.css'), 'utf8');
  if (actualCSS !== fontCSS(result.manifest, result.base)) throw new Error('Font CSS is stale; run npm run fonts:sync.');
  return result;
}
